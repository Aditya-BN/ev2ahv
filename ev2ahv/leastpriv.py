"""Least-privilege everRun host account (D27): the exact sudoers allowlist and the one-time node setup.

The engine reaches an everRun node as a normal user and runs only these through `sudo -n`:
  - `virsh -r list --all --name`, `virsh -r domstate <vm>`, `virsh -r dumpxml <vm>` (read-only libvirt);
  - the ev2ahv helper's read-only ops `caps`, `size`, `hash`, `read` on a path below the everRun volume path.
Nothing else needs sudo: no writes on the node, no file copied there per run. The helper is installed once, root-owned,
because sudo must never run a file the unprivileged user could edit. A root-owned `allowed-prefix` file makes the
helper itself refuse paths outside the storage path (sudoers `*` also matches `..`) and refuse `write`.
"""
import hashlib, re, shlex

from . import transport

USER_RE = re.compile(r"^[a-z_][a-z0-9_-]{0,31}$")
PATH_RE = re.compile(r"^/[\w./-]*$")
SUDOERS_FILE = "/etc/sudoers.d/ev2ahv"
HELPER_DIR = "/usr/local/libexec/ev2ahv"


def check_inputs(user, storage_path):
    if not USER_RE.match(user or "") or user == "root":
        raise ValueError("ssh user must be a lowercase unix account name other than root")
    if not PATH_RE.match(storage_path or "") or storage_path.count("/") < 2 or ".." in storage_path.split("/"):
        raise ValueError("storage path must be an absolute path at least two levels deep, e.g. /mnt/everrun")


def allowlist(storage_path="/mnt/everrun"):
    """The exact sudo command patterns (what the engine builds; tests keep both in step)."""
    py, helper, virsh = transport.PYTHON3, transport.HELPER_INSTALLED, transport.VIRSH
    base = f"{py} -I {helper}"
    sp = storage_path.rstrip("/")
    return [f"{virsh} -r list --all --name",
            f"{virsh} -r domstate *",
            f"{virsh} -r dumpxml *",
            f"{base} caps",
            f"{base} size {sp}/*",
            f"{base} hash {sp}/*",
            f"{base} read {sp}/*"]


def sudoers_snippet(user, storage_path="/mnt/everrun"):
    check_inputs(user, storage_path)
    rules = ",\\\n    ".join(allowlist(storage_path))
    return (f"# {SUDOERS_FILE}: ev2ahv read-only access (generated by ev2ahv, see docs/least-privilege.md)\n"
            f"Cmnd_Alias EV2AHV_READ = \\\n    {rules}\n"
            f"Defaults:{user} !requiretty\n"
            f"{user} ALL=(root) NOPASSWD: EV2AHV_READ\n")


def helper_sha256():
    with open(transport.HELPER_PATH, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def setup_commands(user, storage_path="/mnt/everrun"):
    """Shell lines an everRun admin runs once as root on each node (after copying ev2ahv_helper.py next to them)."""
    check_inputs(user, storage_path)
    q = shlex.quote
    snippet = sudoers_snippet(user, storage_path)
    return "\n".join([
        f"# 1. account (skip if it exists), add the appliance public key to ~{user}/.ssh/authorized_keys",
        f"id {q(user)} >/dev/null 2>&1 || useradd -m -s /bin/bash {q(user)}",
        "# 2. helper: root-owned, so sudo never runs a file the account can edit",
        f"install -d -o root -g root -m 0755 {HELPER_DIR}",
        f"install -o root -g root -m 0755 ev2ahv_helper.py {transport.HELPER_INSTALLED}",
        f"echo {q(helper_sha256() + '  ' + transport.HELPER_INSTALLED)} | sha256sum -c -",
        "# 3. the helper reads only below the everRun volume path and never writes",
        f"echo {q(storage_path)} > {HELPER_DIR}/allowed-prefix && chmod 0644 {HELPER_DIR}/allowed-prefix",
        "# 4. sudoers allowlist (checked with visudo before it is installed)",
        f"cat > {SUDOERS_FILE}.new <<'EOF'\n{snippet}EOF",
        f"visudo -cf {SUDOERS_FILE}.new && install -o root -g root -m 0440 {SUDOERS_FILE}.new {SUDOERS_FILE}; rm -f {SUDOERS_FILE}.new",
        ""])


def setup_doc(user, storage_path="/mnt/everrun"):
    """What the UI shows under Environment details, Least-privilege setup."""
    return {"user": user, "storage_path": storage_path, "sudoers": sudoers_snippet(user, storage_path),
            "commands": setup_commands(user, storage_path), "helper_sha256": helper_sha256(),
            "allowlist": allowlist(storage_path)}
